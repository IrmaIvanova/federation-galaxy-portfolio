// Принципы построения:
//     Целостность и последовательность: Единообразие реализации и использования.
//     Автономность: Система как отдельная зависимость (библиотека).
//     Повторное использование: Легкость подключения компонентов в разных проектах.
//     Доступность (Accessibility): Учет потребностей всех пользователей.
//     Надежность: Работа системы с минимальными ошибками.

